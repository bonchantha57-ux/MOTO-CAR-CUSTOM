export const useLanguageStore = defineStore('language', () => {
  const currentLang = ref<LanguageCode>(
    (localStorage.getItem('motocar_lang') as LanguageCode) || 'km'
  )

  const currentOption = computed(() => {
    return LANGUAGE_OPTIONS.find(opt => opt.code === currentLang.value) || LANGUAGE_OPTIONS[1]
  })

  const t = computed(() => {
    return translations[currentLang.value] || translations.en
  })

  function setLanguage(lang: LanguageCode) {
    if (translations[lang]) {
      currentLang.value = lang
      localStorage.setItem('motocar_lang', lang)
      document.documentElement.lang = lang
      document.body.classList.remove('lang-km', 'lang-zh', 'lang-en')
      document.body.classList.add(`lang-${lang}`)
    }
  }

  // Auto-apply on store instantiation
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentLang.value
    document.body.classList.remove('lang-km', 'lang-zh', 'lang-en')
    document.body.classList.add(`lang-${currentLang.value}`)
  }

  return {
    currentLang,
    currentOption,
    t,
    options: LANGUAGE_OPTIONS,
    setLanguage
  }
})
